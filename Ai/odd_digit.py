import tensorflow
from tensorflow import keras
from keras import Sequential
from keras.layers import Dense, Flatten, Conv2D, MaxPool2D, Dropout
import matplotlib.pyplot as plt
import numpy as np
from keras.datasets import mnist

(X_train, y_train),(X_test, y_test)= mnist.load_data()

X_train.shape

X_test.shape

for i in range(10):
  plt.subplot(2,5,i+1)
  plt.imshow(X_train[i])
  plt.title(y_train[i])
  plt.axis("off")

Odd_indecis = y_test % 2 == 1

X_odd = X_test[Odd_indecis]
y_odd = y_test[Odd_indecis]

for i in range(10):
    plt.subplot(2, 5, i + 1)
    plt.imshow(X_odd[i], cmap='gray')
    plt.title(y_odd[i])
    plt.axis('off')

X_train = X_train/255.0
X_test = X_test/255.0

X_train[2]

model = Sequential()

model.add(Conv2D( 32, kernel_size = (3,3), padding='same', input_shape=(28,28,1)))
model.add(MaxPool2D((2,2)))

model.add(Conv2D( 64, kernel_size = (3,3), padding='same'))
model.add(MaxPool2D((2,2)))

model.add(Conv2D( 128, kernel_size = (3,3), padding='same'))
model.add(MaxPool2D((2,2)))

model.add(Flatten())

model.add(Dense(64,activation='relu'))

model.add(Dropout(0.2))

model.add(Dense(32,activation='relu'))
model.add(Dense(10,activation='softmax'))

model.summary()

model.compile(
    optimizer='adam',
    loss='sparse_categorical_crossentropy',
    metrics=['accuracy']
    )

history= model.fit(X_train,y_train,epochs=20, batch_size=32 , validation_split=0.2)

test_loss, test_accuracy = model.evaluate(X_odd, y_odd)
print("Test Loss", test_loss)
print("Test accuracy", test_accuracy)

plt.plot(history.history['loss'],label='training loss')
plt.plot(history.history['val_loss'],label='validation_loss')
plt.show()

plt.plot(history.history['accuracy'],label='training accuracy')
plt.plot(history.history['val_accuracy'],label='validation accuracy')
plt.show()

plt.imshow(X_odd[3], cmap='gray')
plt.title(y_odd[3])

prediction = model.predict(X_odd[3].reshape(1,28,28,1))
